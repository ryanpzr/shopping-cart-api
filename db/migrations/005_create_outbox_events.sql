-- 005_create_outbox_events.sql
-- Module: 06-activity-log (sdd/specs/modules/06-activity-log.md)
-- Transactional outbox: the API inserts a row here in the same transaction as the
-- business change; Debezium reads the inserts from the WAL and publishes them to Kafka.
-- Applied automatically by the postgres container on first startup
-- (docker-entrypoint-initdb.d runs files in lexical order).

CREATE TABLE IF NOT EXISTS outbox_events (
    id             UUID         PRIMARY KEY,           -- event_id, generated by the API
    aggregate_type VARCHAR(50)  NOT NULL,              -- 'user', 'product', 'cart' or 'order'
    aggregate_id   VARCHAR(50)  NOT NULL,              -- Kafka message key (the user_id)
    event_type     VARCHAR(50)  NOT NULL,              -- see the Event Catalog in the spec
    payload        JSONB        NOT NULL,              -- event_id, user_id, event_type, metadata, occurred_at
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- The purge job deletes rows older than the retention window.
CREATE INDEX IF NOT EXISTS idx_outbox_events_created_at ON outbox_events(created_at);
